-- 2. 군 보급품 사용 대장 테이블 생성
CREATE TABLE IF NOT EXISTS military_supply_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_category VARCHAR(50) NOT NULL,        -- 카테고리 (피복류, 급양/부식, 장구/탄약, 의무, 통신, 정비/소모, 행정 등)
    item_name VARCHAR(100) NOT NULL,            -- 품목명 (예: K2 방한장갑, 전투식량S형 등)
    quantity INT NOT NULL DEFAULT 1,            -- 사용/불출 수량
    unit VARCHAR(20) DEFAULT 'EA',              -- 단위 (EA, 박스, 캔, 세트 등)
    user_name VARCHAR(50) NOT NULL,             -- 작성자/불출자 (예: 김병장, 통신소대 하사 홍길동)
    purpose TEXT NOT NULL,                      -- 사용 목적 / 불출 사유 (예: 야간 경계근무 불출)
    memo TEXT,                                  -- 특이사항 및 메모 (사용자 메모)
    status VARCHAR(20) DEFAULT '불출완료',      -- 상태 (불출완료, 사용중, 반납완료, 폐기소모)
    used_at TIMESTAMPTZ DEFAULT NOW(),          -- 사용 일시
    created_at TIMESTAMPTZ DEFAULT NOW()        -- 등록 일시
);

-- 3. Row Level Security (RLS) 활성화
-- Supabase의 보안 정책 기능을 켭니다.
ALTER TABLE military_supply_ledger ENABLE ROW LEVEL SECURITY;

-- 4. 공개 접속 허용 정책 (누구나 읽고 작성할 수 있도록 설정)
-- 누구나 대장 목록 조회 가능 (SELECT)
CREATE POLICY "누구나 대장 조회 가능" 
ON military_supply_ledger 
FOR SELECT 
USING (true);

-- 누구나 대장 작성 가능 (INSERT)
CREATE POLICY "누구나 대장 등록 가능" 
ON military_supply_ledger 
FOR INSERT 
WITH CHECK (true);

-- (선택 사항) 상태 업데이트 허용 정책
CREATE POLICY "누구나 대장 상태 변경 가능" 
ON military_supply_ledger 
FOR UPDATE 
USING (true);

